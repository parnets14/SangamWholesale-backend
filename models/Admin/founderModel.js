const mongoose = require("mongoose");

const founderSchema = mongoose.Schema(
  {
    name: {
      type: String,
      required: [true, "Name is required"],
      trim: true,
    },
    description: {
      type: String,
      default: "",
    },
    image: {
      type: String,
      default: "",
    },
  },
  {
    timestamps: true,
  }
);

const Founder = mongoose.model("Founder", founderSchema);
module.exports = Founder;
